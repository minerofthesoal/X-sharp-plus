/* ===== Create Project ===== */
bool xs_create_project(const char* name, const char* template_name) {
    if (!name || !template_name)
        return false;

    /* Determine the base directory */
    char base_dir[1024];
    bool is_init = (strcmp(name, ".") == 0);
    if (is_init) {
        snprintf(base_dir, sizeof(base_dir), ".");
    } else {
        snprintf(base_dir, sizeof(base_dir), "%s", name);
        if (!ensure_dir(base_dir)) {
            fprintf(stderr, "Cannot create directory: %s\n", base_dir);
            return false;
        }
    }

    /* Determine template */
    const char* main_content = NULL;
    XsProjectTemplate tmpl;

    if (strcmp(template_name, "console") == 0) {
        tmpl = TEMPLATE_CONSOLE;
        main_content = CONSOLE_MAIN;
    } else if (strcmp(template_name, "game") == 0) {
        tmpl = TEMPLATE_GAME;
        main_content = GAME_MAIN;
    } else if (strcmp(template_name, "ai") == 0) {
        tmpl = TEMPLATE_AI;
        main_content = AI_MAIN;
    } else if (strcmp(template_name, "library") == 0) {
        tmpl = TEMPLATE_LIBRARY;
        main_content = LIBRARY_MAIN;
    } else {
        fprintf(stderr, "Unknown template: %s\n", template_name);
        fprintf(stderr, "Available: console, game, ai, library\n");
        return false;
    }

    /* Create subdirectories */
    char sub[1024];

    snprintf(sub, sizeof(sub), "%s/src", base_dir);
    ensure_dir(sub);

    snprintf(sub, sizeof(sub), "%s/tests", base_dir);
    ensure_dir(sub);

    snprintf(sub, sizeof(sub), "%s/build", base_dir);
    ensure_dir(sub);

    /* Write .xsproj */
    const char* proj_name = is_init ? "my-project" : name;
    write_xsproj(base_dir, proj_name, template_name);

    /* Write main.xs */
    char main_path[1024];
    snprintf(main_path, sizeof(main_path), "%s/main.xs", base_dir);
    write_text_file(main_path, main_content);

    /* Write .gitignore */
    char gi_path[1024];
    snprintf(gi_path, sizeof(gi_path), "%s/.gitignore", base_dir);
    write_text_file(gi_path, "# X# build artifacts\n"
                             "build/\n"
                             "*.xsb\n"
                             "*.Xssc\n"
                             "*.Xscsc\n"
                             "\n"
                             "# IDE\n"
                             ".vscode/\n"
                             ".idea/\n"
                             "\n"
                             "# OS\n"
                             ".DS_Store\n"
                             "Thumbs.db\n");

    /* Template-specific extras */
    if (tmpl == TEMPLATE_LIBRARY) {
        /* Write test file */
        char test_path[1024];
        snprintf(test_path, sizeof(test_path), "%s/tests/test_main.xs", base_dir);
        write_text_file(test_path, LIBRARY_TEST);
    }

    /* Print summary */
    printf("\n%sCreated project structure:%s\n", CLR_BOLD, CLR_RESET);
    printf("  %s%s/%s\n", CLR_CYAN, base_dir, CLR_RESET);
    printf("  %s  .xsproj%s\n", CLR_GREEN, CLR_RESET);
    printf("  %s  .gitignore%s\n", CLR_GREEN, CLR_RESET);
    printf("  %s  main.xs%s\n", CLR_GREEN, CLR_RESET);
    printf("  %s  src/%s\n", CLR_GREEN, CLR_RESET);
    printf("  %s  tests/%s\n", CLR_GREEN, CLR_RESET);
    printf("  %s  build/%s\n", CLR_GREEN, CLR_RESET);
    if (tmpl == TEMPLATE_LIBRARY) {
        printf("  %s  tests/test_main.xs%s\n", CLR_GREEN, CLR_RESET);
    }
    printf("\n  Run with: %sxs run main.xs%s\n", CLR_BOLD, CLR_RESET);

    return true;
}

