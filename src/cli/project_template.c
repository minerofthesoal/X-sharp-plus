/* ===== ANSI Colors ===== */
#define CLR_RESET "\033[0m"
#define CLR_GREEN "\033[32m"
#define CLR_CYAN "\033[36m"
#define CLR_BOLD "\033[1m"

/* ===== Helper: Write a string to a file ===== */
static bool write_text_file(const char* path, const char* content) {
    FILE* f = fopen(path, "w");
    if (!f)
        return false;
    fputs(content, f);
    fclose(f);
    return true;
}

/* ===== Helper: Create a directory (and parent) ===== */
static bool ensure_dir(const char* path) {
    struct stat st;
    if (stat(path, &st) == 0)
        return true; /* already exists */
    return mkdir(path, 0755) == 0;
}

/* ===== .xsproj Template ===== */
static bool write_xsproj(const char* dir, const char* name, const char* tmpl) {
    char path[1024];
    snprintf(path, sizeof(path), "%s/.xsproj", dir);

    char content[2048];
    snprintf(content, sizeof(content),
             "[project]\n"
             "name = \"%s\"\n"
             "version = \"0.1.0\"\n"
             "template = \"%s\"\n"
             "author = \"\"\n"
             "license = \"MIT\"\n"
             "\n"
             "[build]\n"
             "entry = \"main.xs\"\n"
             "output = \"build/\"\n"
             "target = \"native\"\n"
             "\n"
             "[dependencies]\n"
             "# Add dependencies here\n",
             name, tmpl);

    return write_text_file(path, content);
}

